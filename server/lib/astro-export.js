// Export a site version as an Astro + Sanity project (the Kess Media build stack).
// The export reuses the exact renderer the platform hosts with, so what the client
// approved in Kess Cloud is what Astro builds.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SECTION_TYPES } from '../../shared/sections.js';

const sectionsSrc = () => readFileSync(fileURLToPath(new URL('../../shared/sections.js', import.meta.url)), 'utf8');

function sanityField(f) {
  const base = { name: f.key, title: f.label };
  switch (f.type) {
    case 'textarea': case 'richtext': return { ...base, type: 'text', rows: f.type === 'richtext' ? 8 : 3 };
    case 'boolean': return { ...base, type: 'boolean', initialValue: f.default ?? false };
    case 'select': return { ...base, type: 'string', options: { list: f.options }, initialValue: f.default };
    case 'image': return { ...base, type: 'url', validation: '__URL__' };
    case 'list': return { ...base, type: 'array', of: [{ type: 'object', fields: f.fields.map(sanityField) }] };
    default: return { ...base, type: 'string', ...(f.required ? { validation: '__REQ__' } : {}) };
  }
}

export function sanitySchemaJs() {
  const types = Object.entries(SECTION_TYPES).map(([key, def]) => ({
    name: `section_${key}`, title: def.label, type: 'object', fields: def.fields.map(sanityField),
    preview: { select: { title: def.fields.find((f) => f.key === 'heading') ? 'heading' : def.fields[0].key }, prepare: '__PREP__' + def.label },
  }));
  let src = JSON.stringify(types, null, 2)
    .replace(/"__URL__"/g, "(R) => R.uri({ allowRelative: true, scheme: ['http', 'https'] })")
    .replace(/"__REQ__"/g, '(R) => R.required()')
    .replace(/"__PREP__([^"]+)"/g, (_, label) => `({ title }) => ({ title: title || '${label}', subtitle: '${label}' })`);
  return `// Generated by Kess Cloud from shared/sections.js. Regenerate rather than hand-edit.
export const sectionTypes = ${src};

export const page = {
  name: 'page', title: 'Page', type: 'document',
  fields: [
    { name: 'title', title: 'Title', type: 'string', validation: (R) => R.required() },
    { name: 'slug', title: 'Slug (leave empty for home)', type: 'string' },
    { name: 'navLabel', title: 'Menu label', type: 'string' },
    { name: 'description', title: 'Meta description', type: 'text', rows: 3, validation: (R) => R.max(165).warning('Keep under 165 characters') },
    { name: 'inNav', title: 'Show in menu', type: 'boolean', initialValue: true },
    { name: 'sort', title: 'Menu order', type: 'number', initialValue: 0 },
    { name: 'sections', title: 'Sections', type: 'array', of: sectionTypes.map((t) => ({ type: t.name })) },
  ],
  orderings: [{ title: 'Menu order', name: 'sort', by: [{ field: 'sort', direction: 'asc' }] }],
};

export const siteSettings = {
  name: 'siteSettings', title: 'Site settings', type: 'document',
  fields: [
    { name: 'name', title: 'Site name', type: 'string' },
    { name: 'tagline', title: 'Tagline', type: 'string' },
    { name: 'description', title: 'Default meta description', type: 'text', rows: 3 },
    { name: 'email', title: 'Email', type: 'string' },
    { name: 'phone', title: 'Phone', type: 'string' },
    { name: 'address', title: 'Address', type: 'string' },
    { name: 'logo', title: 'Logo URL', type: 'url' },
    { name: 'theme', title: 'Theme (JSON from Kess Cloud)', type: 'text', rows: 6 },
  ],
};

export const schemaTypes = [...sectionTypes, page, siteSettings];
`;
}

export function astroProjectFiles(snapshot, { formAction, hitUrl, siteUrl }) {
  const slug = snapshot.site.slug;
  const files = [];
  const add = (path, content) => files.push({ path, content });

  add('package.json', JSON.stringify({
    name: `${slug}-website`, private: true, type: 'module',
    scripts: { dev: 'astro dev', build: 'astro build', preview: 'astro preview', 'sanity:import': 'node scripts/import-to-sanity.mjs', studio: 'cd studio && npx sanity dev' },
    dependencies: { astro: '^7.4.5', '@sanity/client': '^8.14.1' },
  }, null, 2) + '\n');
  add('astro.config.mjs', `import { defineConfig } from 'astro/config';\n\nexport default defineConfig({\n  site: ${JSON.stringify(siteUrl || 'https://example.com')},\n  output: 'static',\n  trailingSlash: 'ignore',\n});\n`);
  add('.env.example', `# Optional: pull content from Sanity at build time instead of src/content/site.json\nSANITY_PROJECT_ID=\nSANITY_DATASET=production\nSANITY_API_VERSION=2026-01-01\n# Only needed for scripts/import-to-sanity.mjs (Editor token)\nSANITY_WRITE_TOKEN=\n# Kess Cloud endpoints: contact forms land in the client portal inbox\nPUBLIC_FORM_ACTION=${formAction}\nPUBLIC_HIT_URL=${hitUrl}\n`);
  add('.gitignore', 'node_modules\ndist\n.env\n.astro\n');
  add('src/content/site.json', JSON.stringify(snapshot, null, 2) + '\n');
  add('src/lib/sections.js', sectionsSrc());
  add('src/lib/content.js', `import local from '../content/site.json';

// Content source: Sanity when SANITY_PROJECT_ID is set, else the snapshot exported from Kess Cloud.
export async function loadSite() {
  const projectId = import.meta.env.SANITY_PROJECT_ID;
  if (!projectId) return local;
  const { createClient } = await import('@sanity/client');
  const client = createClient({ projectId, dataset: import.meta.env.SANITY_DATASET || 'production', apiVersion: import.meta.env.SANITY_API_VERSION || '2026-01-01', useCdn: false });
  const [settings, pages] = await Promise.all([
    client.fetch('*[_type == "siteSettings"][0]'),
    client.fetch('*[_type == "page"] | order(sort asc)'),
  ]);
  if (!pages?.length) return local;
  let theme = local.theme;
  try { if (settings?.theme) theme = JSON.parse(settings.theme); } catch {}
  return {
    site: { ...local.site, name: settings?.name || local.site.name, settings: { ...local.site.settings, ...strip(settings) } },
    theme,
    pages: pages.map((p) => ({ slug: p.slug || '', title: p.title, navLabel: p.navLabel, description: p.description, inNav: p.inNav !== false,
      sections: (p.sections || []).map((s) => ({ ...strip(s), type: s._type.replace(/^section_/, '') })) })),
  };
}

function strip(o) {
  if (!o) return {};
  const out = {};
  for (const [k, v] of Object.entries(o)) if (!k.startsWith('_')) out[k] = Array.isArray(v) ? v.map((x) => (x && typeof x === 'object' ? strip(x) : x)) : v;
  return out;
}
`);
  add('src/pages/[...slug].astro', `---
import { loadSite } from '../lib/content.js';
import { renderPage } from '../lib/sections.js';

export async function getStaticPaths() {
  const site = await loadSite();
  return site.pages.map((p) => ({ params: { slug: p.slug || undefined }, props: { site, slug: p.slug } }));
}

const { site, slug } = Astro.props;
const html = renderPage(site, slug, {
  base: '',
  formAction: import.meta.env.PUBLIC_FORM_ACTION,
  hitUrl: import.meta.env.PUBLIC_HIT_URL,
  canonicalBase: Astro.site?.toString(),
});
---
<Fragment set:html={html} />
`);
  add('public/robots.txt', `User-agent: *\nAllow: /\n${siteUrl ? `Sitemap: ${siteUrl.replace(/\/$/, '')}/sitemap.xml\n` : ''}`);
  if (siteUrl) add('public/sitemap.xml', sitemapXml(snapshot, siteUrl));
  add('scripts/import-to-sanity.mjs', `// Push src/content/site.json into a Sanity dataset (run once after creating the project).
import { createClient } from '@sanity/client';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';

const { SANITY_PROJECT_ID: projectId, SANITY_DATASET: dataset = 'production', SANITY_WRITE_TOKEN: token } = process.env;
if (!projectId || !token) { console.error('Set SANITY_PROJECT_ID and SANITY_WRITE_TOKEN'); process.exit(1); }
const client = createClient({ projectId, dataset, token, apiVersion: '2026-01-01', useCdn: false });
const site = JSON.parse(readFileSync(new URL('../src/content/site.json', import.meta.url)));
const keyed = (v) => Array.isArray(v) ? v.map((x) => (x && typeof x === 'object' ? { _key: randomUUID().slice(0, 12), ...keyed(x) } : x))
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, keyed(x)])) : v;

const tx = client.transaction();
tx.createOrReplace({ _id: 'siteSettings', _type: 'siteSettings', name: site.site.name, ...site.site.settings, theme: JSON.stringify(site.theme) });
site.pages.forEach((p, i) => tx.createOrReplace({
  _id: 'page-' + (p.slug || 'home'), _type: 'page', title: p.title, slug: p.slug, navLabel: p.navLabel, description: p.description, inNav: p.inNav, sort: i,
  sections: keyed(p.sections.map(({ type, ...rest }) => ({ _type: 'section_' + type, ...rest }))),
}));
await tx.commit();
console.log('Imported', site.pages.length, 'pages into', projectId + '/' + dataset);
`);
  add('studio/package.json', JSON.stringify({ name: `${slug}-studio`, private: true, type: 'module', scripts: { dev: 'sanity dev', deploy: 'sanity deploy' }, dependencies: { sanity: '^6.21.0', '@sanity/vision': '^6.21.0', react: '^19.0.0', 'react-dom': '^19.0.0', 'styled-components': '^6.1.0' } }, null, 2) + '\n');
  add('studio/sanity.config.js', `import { defineConfig } from 'sanity';
import { structureTool } from 'sanity/structure';
import { visionTool } from '@sanity/vision';
import { schemaTypes } from './schemaTypes/index.js';

export default defineConfig({
  name: ${JSON.stringify(slug)},
  title: ${JSON.stringify(snapshot.site.name + ' website')},
  projectId: process.env.SANITY_STUDIO_PROJECT_ID || 'REPLACE_ME',
  dataset: process.env.SANITY_STUDIO_DATASET || 'production',
  plugins: [structureTool(), visionTool()],
  schema: { types: schemaTypes },
});
`);
  add('studio/schemaTypes/index.js', sanitySchemaJs());
  add('README.md', `# ${snapshot.site.name} website

Exported from **Kess Cloud** (Kess Media). Stack: Astro (static) + optional Sanity CMS.

## Run locally

\`\`\`bash
npm install
npm run dev
\`\`\`

Content comes from \`src/content/site.json\` (the version approved in Kess Cloud) until you connect Sanity.

## Connect Sanity

1. Create a project at sanity.io (or with \`npx sanity init\` inside \`studio/\`).
2. Copy \`.env.example\` to \`.env\`, fill \`SANITY_PROJECT_ID\` and an Editor token in \`SANITY_WRITE_TOKEN\`.
3. \`npm run sanity:import\` to load the current pages.
4. \`cd studio && npm install && SANITY_STUDIO_PROJECT_ID=... npm run dev\` to edit content.

## Deploy

\`npm run build\` outputs \`dist/\`. Deploy that folder to Cloudflare Pages, Netlify or any static host.
Contact forms post to Kess Cloud (\`PUBLIC_FORM_ACTION\`) so enquiries keep landing in the client portal.
`);
  return files;
}

export function sitemapXml(snapshot, baseUrl) {
  const b = baseUrl.replace(/\/$/, '');
  const urls = snapshot.pages.map((p) => `  <url><loc>${b}/${p.slug}</loc></url>`).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}
